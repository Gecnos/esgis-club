-- ---------------------------------------------------------------------------------------------
-- Dépôt public d'un dossier (appelé par le formulaire « Créer un club », sans compte)
-- ---------------------------------------------------------------------------------------------

create or replace function public.submit_dossier(payload jsonb) returns text
language plpgsql security definer set search_path = public
as $$
declare
  new_id bigint;
  new_number integer;
  doc jsonb;
begin
  if length(trim(coalesce(payload->>'club_name', ''))) not between 2 and 120
     or length(trim(coalesce(payload->>'porteur', ''))) not between 2 and 120
     or coalesce(payload->>'email', '') !~ '^[^\s@]+@[^\s@]+\.[^\s@]{2,}$'
     or length(regexp_replace(coalesce(payload->>'whatsapp', ''), '\D', '', 'g')) not between 8 and 15
     or length(trim(coalesce(payload->>'contexte', ''))) not between 1 and 4000
     or length(trim(coalesce(payload->>'vision', ''))) not between 1 and 4000 then
    raise exception 'Dossier invalide';
  end if;

  insert into public.dossiers (club_name, porteur, filiere, email, whatsapp, contexte, vision, objectifs, reglement_text, calendar)
  values (
    trim(payload->>'club_name'), trim(payload->>'porteur'), trim(coalesce(payload->>'filiere', '')),
    trim(payload->>'email'), regexp_replace(payload->>'whatsapp', '\D', '', 'g'),
    trim(payload->>'contexte'), trim(payload->>'vision'),
    coalesce(array(select jsonb_array_elements_text(payload->'objectifs')), '{}'),
    nullif(trim(coalesce(payload->>'reglement_text', '')), ''),
    case when jsonb_typeof(payload->'calendar') = 'array' then payload->'calendar' else null end
  )
  returning id, number into new_id, new_number;

  for doc in select * from jsonb_array_elements(coalesce(payload->'documents', '[]'::jsonb)) loop
    insert into public.dossier_documents (dossier_id, kind, name, file_key)
    values (new_id, left(doc->>'kind', 80), left(doc->>'name', 200), nullif(doc->>'file_key', ''));
  end loop;

  return 'CC-' || extract(year from now())::int || '-' || lpad(new_number::text, 3, '0');
end $$;

revoke all on function public.submit_dossier(jsonb) from public;
grant execute on function public.submit_dossier(jsonb) to anon, authenticated;
