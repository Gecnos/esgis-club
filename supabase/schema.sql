-- ---------------------------------------------------------------------------------------------
-- Tables publiques (lues par le site, écrites par les responsables de club et le Comité)
-- ---------------------------------------------------------------------------------------------

create table public.clubs (
  slug              text primary key,
  name              text not null,
  category          text not null check (category in ('Sport', 'Tech', 'Arts & Culture', 'Business & Langues')),
  description       text not null default '',
  members           integer not null default 0,
  founded           integer not null,
  photo_key         text,                 -- vignette de la carte (clé R2)
  cover_photo_id    bigint,               -- photo de couverture, choisie dans club_photos
  logo_key          text,
  schedule          text,
  whatsapp          text,                 -- chiffres seuls, ex. 2290196112233
  long_description  text,
  goal              text,
  objectives        text[] not null default '{}',
  socials           jsonb not null default '{}',
  created_at        timestamptz not null default now()
);

create table public.club_bureau (
  id         bigint generated always as identity primary key,
  club_slug  text not null references public.clubs (slug) on delete cascade,
  role       text not null,
  name       text not null,
  filiere    text not null default '',
  photo_key  text,
  fixed      boolean not null default false,   -- poste obligatoire (Président, Secrétaire, Trésorier, Communication)
  position   integer not null default 0
);

create table public.club_photos (
  id          bigint generated by default as identity primary key,
  club_slug   text not null references public.clubs (slug) on delete cascade,
  label       text not null default '',
  key         text not null,
  ratio       numeric not null default 1.333,   -- largeur / hauteur
  position    integer not null default 0,
  created_at  timestamptz not null default now()
);

create table public.club_activities (
  id         bigint generated always as identity primary key,
  club_slug  text not null references public.clubs (slug) on delete cascade,
  type       text not null,
  title      text not null,
  text       text not null default '',
  photo_key  text,
  position   integer not null default 0
);

-- Activité phare : une seule ligne par club ; elle n'est affichée que pendant le mois du club.
create table public.featured_activities (
  club_slug    text primary key references public.clubs (slug) on delete cascade,
  title        text not null,
  start_time   time not null default '12:00',
  end_time     time not null default '17:00',
  place        text not null default '',
  description  text not null default '',
  visual_key   text,
  program      jsonb not null default '[]'     -- [{ "time": "12:00", "label": "…" }]
);

-- Club du mois : une ligne par mois (premier jour du mois). Un club ne peut être programmé qu'une fois par année universitaire.
create table public.planning (
  month      date primary key check (extract(day from month) = 1),
  club_slug  text references public.clubs (slug),
  vacation   boolean not null default false,
  check (not (vacation and club_slug is not null))
);
create unique index planning_club_once_per_season on public.planning (
  club_slug,
  (case when extract(month from month) >= 9 then extract(year from month) else extract(year from month) - 1 end)
) where club_slug is not null;

create table public.committee_members (
  id         bigint generated always as identity primary key,
  role       text not null,
  name       text not null,
  filiere    text not null default '',
  photo_key  text,
  position   integer not null default 0
);

create table public.challenge_scores (
  club_slug   text primary key references public.clubs (slug) on delete cascade,
  points      integer not null default 0,
  updated_at  date not null default current_date
);

create table public.club_log (
  id          bigint generated always as identity primary key,
  club_slug   text not null references public.clubs (slug) on delete cascade,
  icon        text not null default 'edit',
  text        text not null,
  who         text not null,
  created_at  timestamptz not null default now()
);

-- ---------------------------------------------------------------------------------------------
-- Dossiers de création de club (déposés depuis le site, traités par le Comité)
-- ---------------------------------------------------------------------------------------------

create sequence public.dossier_number_seq start 1;

create table public.dossiers (
  id              bigint generated always as identity primary key,
  number          integer not null default nextval('public.dossier_number_seq'),
  club_name       text not null,
  porteur         text not null,
  filiere         text not null,
  email           text not null,
  whatsapp        text not null,
  contexte        text not null,
  vision          text not null,
  objectifs       text[] not null default '{}',
  reglement_text  text,
  calendar        jsonb,
  status          text not null default 'recu' check (status in ('recu', 'etude', 'soutenance', 'approuve', 'rejete')),
  deposited_at    timestamptz not null default now(),
  defense_at      timestamptz,
  decided_at      timestamptz,
  motif           text
);

create table public.dossier_documents (
  id          bigint generated always as identity primary key,
  dossier_id  bigint not null references public.dossiers (id) on delete cascade,
  kind        text not null,
  name        text not null,
  file_key    text                              -- clé R2 ; null si saisi en texte ou en tableau
);

-- ---------------------------------------------------------------------------------------------
-- Profils : lient un compte Supabase Auth à un rôle. Créés à la main par le Comité (voir docs/supabase.md).
-- ---------------------------------------------------------------------------------------------

create table public.profiles (
  id         uuid primary key references auth.users (id) on delete cascade,
  full_name  text,
  role       text not null check (role in ('club', 'comite')),
  club_slug  text references public.clubs (slug),
  check ((role = 'club') = (club_slug is not null))
);

create or replace function public.app_role() returns text
language sql stable security definer set search_path = public
as $$ select role from public.profiles where id = auth.uid() $$;

create or replace function public.app_club() returns text
language sql stable security definer set search_path = public
as $$ select club_slug from public.profiles where id = auth.uid() $$;

-- Un responsable de club ne modifie ni le nom, ni la catégorie, ni les chiffres de son club : c'est le rôle du Comité.
create or replace function public.clubs_guard() returns trigger
language plpgsql security definer set search_path = public
as $$
begin
  if coalesce(public.app_role(), '') <> 'comite'
     and (new.slug, new.name, new.category, new.members, new.founded, new.photo_key)
         is distinct from (old.slug, old.name, old.category, old.members, old.founded, old.photo_key) then
    raise exception 'Seul le Comité peut modifier le nom, la catégorie ou les chiffres d''un club';
  end if;
  return new;
end $$;
create trigger clubs_guard before update on public.clubs for each row execute function public.clubs_guard();

